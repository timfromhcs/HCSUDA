"""Embed a directory of installer files as a C byte array for the native setup EXE.

Format (all little-endian):
  magic "HCSPAK01", uint32 file_count
  per file: uint32 name_len, uint8 name[name_len], uint64 size, uint8 data[size]

Names are base names only; the native installer rejects separators and '..'.
"""
import argparse
import pathlib
import struct

MAGIC = b"HCSPAK01"


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--input", required=True)
    parser.add_argument("--output", required=True)
    args = parser.parse_args()

    root = pathlib.Path(args.input)
    files = sorted(p for p in root.rglob("*") if p.is_file())
    payload = bytearray(MAGIC)
    payload += struct.pack("<I", len(files))
    for path in files:
        name = path.name.encode("utf-8")
        data = path.read_bytes()
        payload += struct.pack("<I", len(name)) + name
        payload += struct.pack("<Q", len(data)) + data

    lines = [
        "/* Generated by installer/embed_payload.py. Do not edit. */",
        "#pragma once",
        "#include <cstddef>",
        "extern const unsigned char g_setup_payload[];",
        "extern const size_t g_setup_payload_len;",
        "const unsigned char g_setup_payload[] = {",
    ]
    for i in range(0, len(payload), 24):
        chunk = payload[i:i + 24]
        lines.append("    " + ",".join(f"0x{b:02x}" for b in chunk) + ",")
    lines.append("};")
    lines.append(f"const size_t g_setup_payload_len = {len(payload)}u;")
    pathlib.Path(args.output).write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"embedded {len(files)} files, {len(payload)} bytes")


if __name__ == "__main__":
    main()
